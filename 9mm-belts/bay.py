#!/usr/bin/env python3
"""Plan views of the bays with the upper plates and everything above them left out: bay-<corner>.png. Run after drive.py. usage: python3 bay.py [rcad]"""
import json, subprocess, sys
m = json.load(open("drive-parts.json"))["hardware"]
cols = "[" + ", ".join('"%s"' % p["color"] for p in m) + "]"
V = {"rear-left": (402, 435, 467.0), "rear-right": (402, 18, 461.0), "front-left": (1, 433, 467.0), "front-right": (1, 20, 461.0)}
src = 'let hw = import_step("drive-hardware.step").solids(); let pl = import_step("drive-plates.step").solids(); let cols = %s;\n' % cols
for n, (x, y, z) in V.items():
    src += '''{ let box = block(vec3(%f, %f, 400), vec3(%f, %f, %f)); let show = [];
  for i in 0..hw.len() { let b = hw[i].bbox(); if b.max.z < %f + 0.3 && b.min.x > %f && b.max.x < %f && b.min.y > %f && b.max.y < %f || i >= hw.len() - 2 { show.push(#{shape: hw[i] & box, color: cols[i]}); } }
  for p in pl { let b = p.bbox(); if b.max.z < %f && b.center.x > %f && b.center.x < %f && b.center.y > %f && b.center.y < %f { show.push(#{shape: p, color: "#b8bec6"}); } }
  render(show, #{path: "bay-%s.png", width: 1300, height: 1300, eye: [%f, %f, 900], target: [%f, %f, 440], up: [1, 0, 0], fov: 0}); }
''' % (x - 50, y - 60, x + 50, y + 60, z, z, x - 60, x + 60, y - 70, y + 70, z, x - 60, x + 60, y - 70, y + 70, n, x, y, x, y)
open("bay.rhai", "w").write("// GENERATED by bay.py\n" + src)
r = subprocess.run([sys.argv[1] if len(sys.argv) > 1 else "rcad", "script", "bay.rhai"], capture_output=True, text=True); print(r.stdout[-500:], r.stderr[-1500:])
