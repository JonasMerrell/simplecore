#!/usr/bin/env python3
"""9 mm belt drive, rev C: the four motor mounts with every component modelled, and both belts.
Writes drive.rhai (the model; the belt outlines come from beltpath.py), runs rcad on it and writes:
  drive.json            rCAD document with the 14 machined parts (feature tree, variables)
  drive-plates.step     the machined parts
  drive-hardware.step   every purchased / turned part and the belts, one solid each
  drive-parts.json      name, colour and material of each solid in drive-hardware.step, and the motor poses
usage: python3 drive.py [path to rcad]"""
import math, json, subprocess, sys, os
import beltpath as bp
HERE = os.path.dirname(os.path.abspath(__file__))
GX, CY = 185.3, 273.8          # model pose: gantry centre x, belt clamp y

def band(circs, teeth_right):
    """Outline of the belt backing (0.62 thick: 0.254 inside the pitch line on the tooth side, 0.368 outside)."""
    segs, wraps, L = bp.path(circs, closed=False)
    o_t, o_b = (-0.254, 0.368) if teeth_right else (0.254, -0.368)     # offsets along the left normal
    def pts(o):
        out = []
        for i, c in enumerate(circs):
            name, x, y, r, s = c
            if i == 0: p, q, t = segs[0]; n = (-math.sin(t), math.cos(t)); out.append((p[0] + o * n[0], p[1] + o * n[1])); continue
            if i == len(circs) - 1: p, q, t = segs[-1]; n = (-math.sin(t), math.cos(t)); out.append((q[0] + o * n[0], q[1] + o * n[1])); continue
            tin, tout = segs[i - 1][2], segs[i][2]
            w = (s * (tout - tin)) % (2 * math.pi)
            k = max(2, int(math.degrees(w) / 4) + 1)
            for j in range(k + 1):
                t = tin + s * w * j / k; n = (-math.sin(t), math.cos(t))
                # pitch point = centre - s*r*n ; offset o along n
                out.append((x - s * r * n[0] + o * n[0], y - s * r * n[1] + o * n[1]))
        return out
    a, b = pts(o_t), pts(o_b)
    return a + b[::-1], L

U, Lb = bp.belts(GX, CY)
bu, lu = band(U, True)
bl, ll = band(Lb, False)
fmt = lambda P: "[" + ", ".join("[%.4f, %.4f]" % p for p in P) + "]"
src = open(os.path.join(HERE, "drive.rhai.in")).read().replace("@BELT_U@", fmt(bu)).replace("@BELT_L@", fmt(bl))
open(os.path.join(HERE, "drive.rhai"), "w").write("// GENERATED by drive.py from drive.rhai.in, do not edit\n" + src)
rcad = sys.argv[1] if len(sys.argv) > 1 else "rcad"
out = subprocess.run([rcad, "script", "drive.rhai"], cwd=HERE, capture_output=True, text=True)
parts, motors = [], []
for line in out.stdout.splitlines():
    f = line.split("|")
    if f[0] == "HW": parts.append({"name": f[1], "color": f[2], "material": f[3] or None})
    elif f[0] == "MOTOR": motors.append({"name": f[1], "t": [float(v) for v in f[2:5]]})
    else: print(line)
if out.returncode: print(out.stderr[-3000:]); sys.exit(1)
json.dump({"hardware": parts, "motors": motors, "belt_length_between_clamps_mm": {"upper": round(lu, 1), "lower": round(ll, 1)}}, open(os.path.join(HERE, "drive-parts.json"), "w"), indent=1)
print(len(parts), "hardware solids,", len(motors), "motors; belt lengths between clamp points %.1f / %.1f mm" % (lu, ll))
